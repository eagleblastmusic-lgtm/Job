import {createHash} from 'node:crypto';
import {writeFile} from 'node:fs/promises';
import {get} from 'node:https';
const version='v1.2.1',scheme='http://data.europa.eu/esco/concept-scheme/member-skills',pageSize=250;
const entries=new Map(),pages=[];
let total;
async function download(url){
 for(let attempt=0;attempt<3;attempt++){
  try{return await new Promise((resolve,reject)=>{
   const req=get(url,{agent:false},response=>{
    if(response.statusCode!==200){response.resume();reject(new Error(`ESCO_HTTP_${response.statusCode}`));return;}
    const chunks=[];let bytes=0;
    response.on('data',chunk=>{bytes+=chunk.length;if(bytes>16*1024*1024){response.destroy(new Error('ESCO_PAGE_TOO_LARGE'));return;}chunks.push(chunk);});
    response.on('error',reject);response.on('end',()=>resolve(Buffer.concat(chunks)));
   });req.setTimeout(30000,()=>req.destroy(new Error('ESCO_TIMEOUT')));req.on('error',reject);
  });}catch(error){if(attempt===2)throw error;await new Promise(resolve=>setTimeout(resolve,1000*(attempt+1)));}
 }
}
for(let offset=0;offset*pageSize<(total??1);offset++){
 const url=new URL('https://ec.europa.eu/esco/api/resource/skill');
 for(const [key,value] of Object.entries({isInScheme:scheme,language:'pl',limit:String(pageSize),offset:String(offset),selectedVersion:version}))url.searchParams.set(key,value);
 const raw=await download(url),data=JSON.parse(raw.toString('utf8'));
 if(!Number.isSafeInteger(data.total)||data.total<1||data.total>20000||data.offset!==offset||data.language!=='pl'||(total!==undefined&&total!==data.total))throw new Error('ESCO_PAGE_CONTRACT');
 total=data.total;
 const records=Object.values(data._embedded??{});
 if(records.length!==Math.min(pageSize,total-offset*pageSize)||data.count!==records.length)throw new Error('ESCO_INCOMPLETE_PAGE');
 for(const concept of records){
  const match=/^http:\/\/data\.europa\.eu\/esco\/skill\/([a-f0-9-]{36})$/.exec(concept.uri??'');
  const label=concept.preferredLabel?.pl,aliases=concept.alternativeLabel?.pl??[];
  if(!match||concept.status!=='released'||!concept._links?.isInScheme?.some(s=>s.uri===scheme)||typeof label!=='string'||!label.trim()||label.length>500||!Array.isArray(aliases)||aliases.some(a=>typeof a!=='string'||!a.trim()||a.length>500)||entries.has(match[1]))throw new Error('ESCO_CONCEPT_CONTRACT');
  entries.set(match[1],[match[1],label,[...new Set(aliases)]]);
 }
 pages.push({offset,count:records.length,sha256:createHash('sha256').update(raw).digest('hex')});
 console.log(`ESCO_PAGE_PASS offset=${offset} count=${records.length}`);
}
if(entries.size!==total)throw new Error('ESCO_TOTAL_MISMATCH');
const sorted=[...entries.values()].sort((a,b)=>a[0].localeCompare(b[0])),serialized=JSON.stringify(sorted);
const manifest={version,scheme,language:'pl',count:total,retrievedAt:new Date().toISOString(),endpoint:'https://ec.europa.eu/esco/api/resource/skill',licenseNotice:'https://esco.ec.europa.eu/en/copyright-notice-esco-skills-competences',license:'CC-BY-4.0',attribution:'European Commission, ESCO Skills Pillar v1.2.1; Polish preferred/alternative labels. Extracted member-skills labels only; no hierarchy, descriptions, occupations, qualifications or third-party source material imported. No endorsement or equivalence with Faro authored concepts implied.',changes:'Selected Polish labels/aliases; sorted by URI; added independent ESCO IDs. Source labels unchanged.',dataSha256:createHash('sha256').update(serialized).digest('hex'),pages};
await writeFile(new URL('../src/domain/faro/escoCatalogData.ts',import.meta.url),`/** Generated by scripts/import-esco-skills.mjs. See ESCO_SKILLS_MANIFEST.json for source/attribution. */\nexport const ESCO_SKILLS:readonly [string,string,string[]][]=${serialized};\n`);
await writeFile(new URL('../docs/faro/ESCO_SKILLS_MANIFEST.json',import.meta.url),JSON.stringify(manifest,null,2)+'\n');
console.log(`ESCO_IMPORT_PASS count=${total} sha256=${manifest.dataSha256}`);
